/// Display color maps applied after windowing.
enum DicomColorMap {
  /// Standard grayscale display.
  grayscale,

  /// Hot-iron heat scale.
  hotIron,

  /// PET color scale.
  pet,

  /// Rainbow color scale.
  rainbow,

  /// Cool blue-to-cyan scale.
  cool,

  /// Bone grayscale with warm tint.
  bone,
}
